# zonetariff.py
"""
ZoneTariff: a LOCAL market provider for a fixed time-of-use tariff
(HT/NT, "Optima", night tariff, ...). No network, no API key -- the
prices come straight from the config.

Config (per market entry):

    zones_summer : "00:00-06:00=22.0; 06:00-22:00=31.0; 22:00-24:00=24.0"
    zones_winter : "00:00-06:00=25.0; 06:00-22:00=34.0; 22:00-24:00=27.0"
    summer_months: "4-9"        (default; every other month is winter)
    fee          : ""           (optional, net price is the default)

Window syntax: `from-to=price` entries, separated by ';', ',' or a
newline. Times are local wall-clock `HH:MM` (the short `H` form works
too, `24:00` closes the day). Prices are NET ct/kWh, exactly like the
fee-based markets: the usual chain still applies (market fee,
{grid_fee} token / automatic grid fee, vat_percent), because the
price is handed to Item with potency 14 -- the ct/kWh storage unit.

A window may cross midnight (`22:00-06:00=24.0`). Boundaries snap to
the 15-minute grid the rest of SEUSS works on. The FIRST window wins
on overlap; quarters no window covers are filled with the HIGHEST
defined price -- never with 0 or the cheapest one, because a config
gap must not look like "free electricity" to the charging logic.

Season: a month listed in `summer_months` uses zones_summer, every
other month uses zones_winter. Leave one of the two zone strings empty
and the other one applies all year (logged as a hint). Both empty ->
no items -> the normal failback-market path of Itemlist kicks in (a
broken tariff config never produces prices).

DST: items are generated by walking UTC quarters and looking up the
LOCAL wall clock per quarter. Spring-forward days simply lose the
skipped hour, fall-back days repeat one hour at its wall-clock price,
and the item chain stays gap-free either way -- no pytz special cases.
"""

import re
from datetime import datetime, timedelta

import pytz

from core.log import CustomLogger
from core.timeutilities import TimeUtilities
from spotmarket.abstract_classes.item import Item
from spotmarket.abstract_classes.marketdata import MarketData

# Quarter resolution is the SEUSS-internal grid (see Itemlist).
QUARTER_MINUTES = 15
SLOTS_PER_HOUR = 60 // QUARTER_MINUTES
SLOTS_PER_DAY = 24 * SLOTS_PER_HOUR

# Template defaults (examples live in core/config.py -- the user edits
# them in the config editor before enabling the market).
DEFAULT_SUMMER_MONTHS = "4-9"

# One window: `from-to=price`, tolerant about spaces and a comma
# decimal separator. Windows are separated by ';', a newline, or a
# comma that is followed by the next `from-to` pair (so a decimal
# comma like "31,5" is never mistaken for a separator).
_WINDOW_RE = re.compile(
    r"^\s*(?P<start>\d{1,2}(?::\d{1,2})?)\s*-\s*"
    r"(?P<end>\d{1,2}(?::\d{1,2})?)"
    r"\s*=\s*(?P<price>\d+(?:[.,]\d+)?)\s*$"
)
_WINDOW_SPLIT_RE = re.compile(
    r"[;\n\r]+|,(?=\s*\d{1,2}(?::\d{1,2})?\s*-)")


class ZonetariffItem(Item):
    def __init__(self, starttime, endtime, price, fee_str):
        # Potency 14: the zone price is already ct/kWh, which is the
        # unit every consumer works with (Utils.millicent_to_cent
        # divides by 10^14). The spot providers pass EUR/MWh with
        # potency 13; both end up at the same stored scale, so fee,
        # {grid_fee} and vat_percent maths are identical.
        super().__init__(starttime, endtime, price, fee_str, 14)


class Zonetariff(MarketData):
    def __init__(self, **kwargs) -> None:
        super().__init__(**kwargs)
        self.zones_summer = kwargs.get("zones_summer", "") or ""
        self.zones_winter = kwargs.get("zones_winter", "") or ""
        self.summer_months = kwargs.get(
            "summer_months", DEFAULT_SUMMER_MONTHS)
        # Parsed state, rebuilt only when the specs change.
        self._cache_key = None
        self._summer_table = None
        self._winter_table = None
        self._summer_month_set = frozenset(range(4, 10))

    # ------------------------------------------------------------------
    # Parsing helpers (pure, static -- also used by the unit tests)
    # ------------------------------------------------------------------

    @staticmethod
    def parse_months(spec):
        """
        Parse a month list into a set of ints. Accepts "4-9", "4,5,6",
        "10-3" (wrap) and a bare number (an int from a config save).
        Unknown parts are skipped; the caller decides about defaults.
        """
        if isinstance(spec, (int, float)):
            spec = str(int(spec))
        if not isinstance(spec, str):
            return set()
        months = set()
        for part in spec.replace(";", ",").split(","):
            part = part.strip()
            if not part:
                continue
            try:
                if "-" in part:
                    first, last = part.split("-", 1)
                    first, last = int(first), int(last)
                    if first <= last:
                        months.update(range(first, last + 1))
                    else:
                        months.update(range(first, 13))
                        months.update(range(1, last + 1))
                else:
                    months.add(int(part))
            except (TypeError, ValueError):
                continue
        return {month for month in months if 1 <= month <= 12}

    @staticmethod
    def _parse_clock(text):
        """'6', '06:00', '6:30', '24:00' -> minutes since midnight."""
        text = text.strip()
        if ":" in text:
            hour_text, minute_text = text.split(":", 1)
        else:
            hour_text, minute_text = text, "0"
        try:
            hour, minute = int(hour_text), int(minute_text)
        except (TypeError, ValueError):
            raise ValueError(f"invalid time '{text}'")
        if hour == 24 and minute == 0:
            return 24 * 60
        if not (0 <= hour < 24 and 0 <= minute < 60):
            raise ValueError(f"invalid time '{text}'")
        return hour * 60 + minute

    @staticmethod
    def _snap(minutes):
        """Snap a minute-of-day boundary to the 15-minute grid."""
        return int(round(minutes / QUARTER_MINUTES)) * QUARTER_MINUTES

    @classmethod
    def parse_windows(cls, spec):
        """
        Parse a zone spec into [(start_min, end_min, price_ct)].
        Empty/blank -> []. Malformed input raises ValueError (the
        market reports no prices then instead of inventing some).
        """
        if not isinstance(spec, str):
            raise ValueError("zone spec must be a string")
        windows = []
        for chunk in _WINDOW_SPLIT_RE.split(spec):
            chunk = chunk.strip()
            if not chunk:
                continue
            match = _WINDOW_RE.match(chunk)
            if not match:
                raise ValueError(f"invalid zone window '{chunk}'")
            price = float(match.group("price").replace(",", "."))
            if not price > 0.0:
                raise ValueError(
                    f"price must be > 0 in window '{chunk}' "
                    f"(0 would look like free electricity to the "
                    f"charging logic)")
            start = cls._snap(cls._parse_clock(match.group("start")))
            end = cls._snap(cls._parse_clock(match.group("end")))
            start %= 24 * 60
            if end == 0:
                # '...-00:00' closes the day at midnight.
                end = 24 * 60
            windows.append((start, end, price))
        return windows

    @classmethod
    def _window_slots(cls, start, end):
        """Quarter-slot indices covered by one window (wrap aware)."""
        if end == start:
            # '06:00-06:00' = the whole day.
            return range(0, SLOTS_PER_DAY)
        first = start // QUARTER_MINUTES
        if end > start:
            return range(first, min(end, 24 * 60) // QUARTER_MINUTES)
        # Window crosses midnight: start..24:00 plus 00:00..end.
        return list(range(first, SLOTS_PER_DAY)) + list(
            range(0, end // QUARTER_MINUTES))

    @staticmethod
    def _minute_to_text(minutes):
        if minutes >= 24 * 60:
            return "24:00"
        return f"{minutes // 60:02d}:{minutes % 60:02d}"

    @classmethod
    def _slots_to_text(cls, slots):
        """
        Compress slot indices into readable window ranges, e.g.
        [0..23] -> '00:00-06:00'. Non-contiguous sets are split.
        """
        if not slots:
            return ""
        ordered = sorted(set(slots))
        ranges = []
        first = last = ordered[0]
        for slot in ordered[1:]:
            if slot == last + 1:
                last = slot
                continue
            ranges.append((first, last))
            first = last = slot
        ranges.append((first, last))
        return ", ".join(
            f"{cls._minute_to_text(start * QUARTER_MINUTES)}-"
            f"{cls._minute_to_text(min((stop + 1) * QUARTER_MINUTES, 24 * 60))}"
            for start, stop in ranges
        )

    @classmethod
    def build_table(cls, spec):
        """
        Build the 96-slot price table (ct/kWh) for one season. None
        when the spec is empty. Raises ValueError on malformed input.
        """
        windows = cls.parse_windows(spec)
        if not windows:
            return None

        logger = CustomLogger().log
        table = [None] * SLOTS_PER_DAY
        overlapping = []
        for start, end, price in windows:
            for slot in cls._window_slots(start, end):
                if table[slot] is None:
                    table[slot] = price
                elif table[slot] != price:
                    overlapping.append(slot)

        gaps = [slot for slot, value in enumerate(table) if value is None]
        if gaps:
            # Fail-safe: a gap must never look cheaper than a real
            # zone, otherwise a typo would trigger charging.
            fill = max(price for _, _, price in windows)
            for slot in gaps:
                table[slot] = fill
            logger.warning(
                f"Zonetariff: zone spec has uncovered hours "
                f"({cls._slots_to_text(gaps)}); filled with the highest "
                f"defined price {fill:.2f} ct/kWh."
            )
        if overlapping:
            logger.warning(
                f"Zonetariff: overlapping zone windows "
                f"({cls._slots_to_text(overlapping)}); the first window "
                f"in the spec wins."
            )
        return [float(value) for value in table]

    @classmethod
    def describe_windows(cls, spec):
        """Short log-friendly summary of a parsed zone spec."""
        windows = cls.parse_windows(spec)
        return ", ".join(
            f"{cls._minute_to_text(start)}-{cls._minute_to_text(end)}="
            f"{price:.2f}ct"
            for start, end, price in windows
        )

    # ------------------------------------------------------------------
    # Parsed state
    # ------------------------------------------------------------------

    def _warn_on_hourly_collapse(self, table, season):
        """
        Itemlist averages the four quarters of an hour when
        tariff_resolution is 'hourly'. That silently flattens a zone
        boundary sitting inside an hour (e.g. 06:30) -- warn once.
        """
        try:
            from core.config import Config
            resolution = getattr(Config(), "tariff_resolution", "hourly")
        except Exception:
            resolution = "hourly"
        if resolution != "hourly":
            return
        mixed = [
            hour for hour in range(24)
            if len({table[hour * SLOTS_PER_HOUR + i]
                    for i in range(SLOTS_PER_HOUR)}) > 1
        ]
        if mixed:
            self.logger.log.warning(
                f"Zonetariff: {season} zones change inside the hour "
                f"({', '.join(f'{hour:02d}:00' for hour in mixed)}). "
                f"tariff_resolution is 'hourly', so SEUSS averages those "
                f"quarters; set tariff_resolution to 'quarterly' to keep "
                f"the zone boundary exact."
            )

    def _ensure_tables(self):
        """Parse + cache both season tables. False when unusable."""
        key = (str(self.zones_summer), str(self.zones_winter),
               str(self.summer_months))
        if self._cache_key == key and self._summer_table is not None:
            return True

        summer_spec = str(self.zones_summer or "").strip()
        winter_spec = str(self.zones_winter or "").strip()
        if not summer_spec and not winter_spec:
            self.logger.log.error(
                "Zonetariff: both zones_summer and zones_winter are empty. "
                "No prices can be generated."
            )
            return False

        try:
            summer_table = (Zonetariff.build_table(summer_spec)
                            if summer_spec else None)
            winter_table = (Zonetariff.build_table(winter_spec)
                            if winter_spec else None)
        except ValueError as e:
            self.logger.log.error(
                f"Zonetariff: invalid zone configuration: {e}. "
                f"No prices can be generated."
            )
            self._cache_key = None
            return False

        if summer_table is None and winter_table is None:
            self.logger.log.error(
                "Zonetariff: no usable zone windows found in the "
                "configuration. No prices can be generated."
            )
            return False
        if summer_table is None:
            self.logger.log.info(
                "Zonetariff: zones_summer is empty -- the winter zones "
                "apply all year."
            )
            summer_table = winter_table
        if winter_table is None:
            self.logger.log.info(
                "Zonetariff: zones_winter is empty -- the summer zones "
                "apply all year."
            )
            winter_table = summer_table

        months = Zonetariff.parse_months(self.summer_months)
        if not months:
            months = Zonetariff.parse_months(DEFAULT_SUMMER_MONTHS)
            self.logger.log.warning(
                f"Zonetariff: summer_months '{self.summer_months}' is not "
                f"usable, falling back to '{DEFAULT_SUMMER_MONTHS}'."
            )

        self._summer_table = summer_table
        self._winter_table = winter_table
        self._summer_month_set = frozenset(months)
        self._cache_key = key

        try:
            self.logger.log.info(
                f"Zonetariff: summer months "
                f"{','.join(str(m) for m in sorted(months))}: "
                f"{Zonetariff.describe_windows(summer_spec) if summer_spec else 'winter zones'}"
            )
            self.logger.log.info(
                f"Zonetariff: winter months "
                f"{','.join(str(m) for m in range(1, 13) if m not in months)}: "
                f"{Zonetariff.describe_windows(winter_spec) if winter_spec else 'summer zones'}"
            )
        except ValueError:
            pass

        if summer_spec:
            self._warn_on_hourly_collapse(summer_table, "summer")
        if winter_spec:
            self._warn_on_hourly_collapse(winter_table, "winter")
        return True

    # ------------------------------------------------------------------
    # Price lookup + generation
    # ------------------------------------------------------------------

    def price_ct_for_local(self, local_dt):
        """
        The tariff price (net ct/kWh) for a LOCAL wall-clock datetime.
        None when the configuration is unusable.
        """
        if not self._ensure_tables():
            return None
        table = (self._summer_table
                 if local_dt.month in self._summer_month_set
                 else self._winter_table)
        slot = (local_dt.hour * SLOTS_PER_HOUR
                + local_dt.minute // QUARTER_MINUTES)
        return table[slot]

    def _generate_items(self, start_utc, end_utc):
        """
        Emit one 15-minute item per UTC quarter in [start_utc, end_utc).
        The LOCAL wall clock of each quarter selects season + window,
        which keeps DST days gap-free (see module docstring).
        """
        items = []
        step = timedelta(minutes=QUARTER_MINUTES)
        cursor = start_utc
        while cursor < end_utc:
            local = TimeUtilities.convert_utc_to_local(cursor, False)
            price = self.price_ct_for_local(local)
            if price is None:
                return []
            items.append(
                ZonetariffItem(cursor, cursor + step, price, self.fee)
            )
            cursor += step
        return items

    @staticmethod
    def _local_midnight_utc(local_date):
        """
        UTC instant of a LOCAL midnight. Midnight is never ambiguous or
        skipped in the supported zones, but we still degrade to the
        standard-time offset instead of raising.
        """
        naive = datetime(local_date.year, local_date.month, local_date.day)
        try:
            localized = TimeUtilities.TZ.localize(naive, is_dst=None)
        except Exception:
            localized = TimeUtilities.TZ.localize(naive, is_dst=False)
        return localized.astimezone(pytz.utc)

    def load_data(self, use_second_day):
        try:
            if not self._ensure_tables():
                return []

            now_local = TimeUtilities.get_now()
            today = now_local.date()
            # A fixed tariff is known in advance, so tomorrow's prices
            # are always delivered (the chart's "tomorrow" tab and the
            # economic horizon need them). use_second_day adds the day
            # after tomorrow, matching the 3-day window of the spot
            # providers.
            days = 3 if use_second_day else 2
            start_utc = self._local_midnight_utc(today)
            end_utc = self._local_midnight_utc(
                today + timedelta(days=days))

            items = self._generate_items(start_utc, end_utc)
            self.logger.log.debug(
                f"Zonetariff: generated {len(items)} quarter items "
                f"from {start_utc} to {end_utc}."
            )
            return items
        except Exception as e:
            # Never let a bad tariff config kill the eval thread.
            self.logger.log.exception(
                f"Unexpected error in Zonetariff load_data: {e}"
            )
            return []
